import {
  DEFAULT_GENERATIVE_UI_LIMITS,
  generativeUiCatalog,
  generativeUiCatalogPrompt,
  generativeUiTurnNote,
  type GenerativeUiLimits
} from './generative-ui'

/**
 * The document for generative UI cards: the contract, the note slackbotv2
 * sends to the agent on the first Slack turn of a thread when the flag is on,
 * and the full catalog prompt json-render generates for deployers who prefer
 * a persona.
 */
export function renderGenerativeUiDoc(limits: GenerativeUiLimits = DEFAULT_GENERATIVE_UI_LIMITS): string {
  const components = generativeUiCatalog.componentNames.join(', ')
  const limitsJson = JSON.stringify(limits)
  return `<!-- Generated by scripts/generate-generative-ui-doc.ts from src/generative-ui.ts. Do not edit by hand. -->
# Generative UI cards in Slack answers

When \`SLACKBOTV2_GENERATIVE_UI_ENABLED\` is on, slackbotv2 turns one fenced
\`json-render\` block in a final answer into a native Slack card (Block Kit)
built with [json-render](https://github.com/vercel-labs/json-render) on the
Chat SDK card model. With the flag on, slackbotv2 also tells the agent about
the card by adding the note below to the first Slack turn it executes in a
thread, next to the Slack session context. Later turns rely on the session's
context; the note is sent again only after a harness restart or when its
content (catalog or limits) changes. No persona or system prompt change is
needed, and other chat surfaces never see the note.

## Contract

- Put at most one fenced block tagged \`json-render\` anywhere in the final
  answer. Prose before and after it stays markdown and streams as usual.
- The block body is either the JSONL patch stream described in the catalog
  prompt below, or one complete flat spec object: \`{"root": "...", "elements": {...}}\`.
- slackbotv2 removes the block from the streamed answer and posts the card as
  a second message in the same thread. If the spec is invalid, exceeds the
  limits, or Slack rejects it, the block is posted as a \`json\` code block
  instead, so nothing is lost, and the \`slackbotv2_generative_ui_cards_total\`
  metric records why.
- Components: ${components}. Buttons that trigger actions are not available;
  use \`LinkButton\` for next steps.
- Default limits per message: \`${limitsJson}\` (\`SLACKBOTV2_GENERATIVE_UI_LIMITS\`).
- When the user asks for "plain text only", "no interactive blocks" or "no
  dashboards", no card is rendered even if a block is present.

## Note sent to the agent on the first Slack turn of a thread

Built from the catalog slackbotv2 validates with (\`@json-render/chat\` standard
components without \`Button\`): the component list and structural rules come
from the catalog, the rest is the fenced-block contract. Skipped on a turn
where the user asked for plain text only (the next turn that allows cards
carries it).

\`\`\`text
${generativeUiTurnNote(limits)}
\`\`\`

## Full catalog prompt

\`catalog.prompt()\` for the same catalog, with the fenced-block rules
appended, for deployers who want to put the long form in a persona or system
prompt instead.

\`\`\`text
${generativeUiCatalogPrompt(limits)}
\`\`\`
`
}
